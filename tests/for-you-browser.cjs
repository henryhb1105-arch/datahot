'use strict';
const {feedNavigation}=require('./browser-readiness.cjs');
const assert = require('node:assert/strict');
const path = require('node:path');
const crypto = require('node:crypto');
const fs = require('node:fs');
module.exports = async function(context, base, out, width) {
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e=>errors.push(e.message));
  await feedNavigation(page, () => page.goto(base+'for-me.html', {waitUntil:'domcontentloaded'}));
  await page.evaluate(()=>{localStorage.removeItem('dh_for_me_v1');localStorage.removeItem('dh_default_home_v1');sessionStorage.clear();});
  await feedNavigation(page, () => page.reload({waitUntil:'domcontentloaded'}));
  await page.locator('#fmContent').waitFor();
  const asset = new URL(await page.locator('script[src*="for-me.js?"]').getAttribute('src'), base);
  const response = await context.request.get(asset.href);
  assert(response.ok());
  assert.equal(crypto.createHash('sha256').update(await response.body()).digest('hex').slice(0,12), asset.searchParams.get('v'), 'Personalization asset hash');
  assert(!(await page.locator('#fmSettings').isVisible()), 'First visit starts with articles, not setup');
  const firstCard = page.locator('#fmMustList .fm-signal').first();
  await firstCard.waitFor();
  assert((await page.locator('#fmFeedList .fm-signal').count()) > 0, 'New visitors can continue reading beyond three picks');
  assert(!(await page.locator('#fmReadList').isVisible()), 'Empty read-history does not occupy the feed');
  const initial = await firstCard.boundingBox();
  assert(initial.y < 200, `First article starts at ${initial.y}px`);
  const reason = await firstCard.locator('.fm-why').boundingBox();
  assert(reason.y + reason.height < 780, 'Recommendation reason is readable in first mobile viewport');
  assert.equal(await page.locator('.fm-hero').evaluate(el=>getComputedStyle(el).position), 'static');
  await page.screenshot({path:path.join(out,`${width}-for-you-first.png`)});
  const href=await firstCard.locator('.fm-signal-title').getAttribute('href');
  await firstCard.locator('.fm-signal-title').click();
  await page.waitForURL(new URL(href,base).href);
  await feedNavigation(page, () => page.goBack({waitUntil:'domcontentloaded'}));
  assert(!(await page.locator('#fmSettings').isVisible()), 'Reading and back do not open setup');
  await page.locator('#fmCustomize').click();
  assert(await page.locator('#fmTaskStep').isVisible());
  const panel = await page.locator('#fmSettings').boundingBox();
  if(width>600) assert(Math.abs(panel.x+panel.width/2-width/2)<2, 'Desktop settings are centered despite global margin reset');
  else assert(Math.abs(panel.width-width)<2, 'Mobile settings use the viewport width');
  for (let i=0;i<18;i++) {await page.keyboard.press('Tab');assert(await page.locator('#fmSettings').evaluate(el=>el.contains(document.activeElement)||document.activeElement===document.body), 'Keyboard cannot focus the background feed while settings are modal');}
  await page.keyboard.press('Escape');
  assert(!(await page.locator('#fmSettings').isVisible()));
  assert(await page.locator('#fmCustomize').evaluate(el=>el===document.activeElement), 'Escape restores focus');
  await page.locator('#fmCustomize').click();
  await page.locator('#fmSkip').click();
  assert(!(await page.locator('#fmSetup').isVisible()));
  await page.locator('#fmCustomize').click();
  await page.mouse.click(5,5);
  await page.locator('#fmSettings').waitFor({state:'hidden'});
  await page.locator('#fmCustomize').click();
  await page.locator('[data-task="agent"]').click();
  await page.locator('#fmNext').click();
  assert(await page.locator('#fmFollowStep').isVisible());
  await page.locator('#fmDone').click();
  assert(await page.locator('#fmWork').isVisible());
  const first = page.locator('#fmMustList .fm-signal').first();
  await first.waitFor();
  const id = await first.getAttribute('data-event-id');
  assert.match(await first.locator('.fm-why').innerText(), /搭建 Data Agent/);
  await first.locator('[data-action="read"]').click();
  assert.equal(await page.locator(`#fmMustList [data-event-id="${id}"]`).count(), 0);
  const dismiss = page.locator('#fmMustList .fm-signal').first();
  const dismissId = await dismiss.getAttribute('data-event-id');
  await dismiss.locator('[data-action="dismiss"]').click();
  await page.locator('#fmNotice button').click();
  assert.equal(await page.locator(`#fmMustList [data-event-id="${dismissId}"]`).count(), 1);
  await page.locator('#fmCustomize').click();
  await page.locator('#fmDefaultHome').check();
  await page.locator('#fmCloseSettings').click();
  await page.goto(base, {waitUntil:'networkidle'});
  await page.waitForURL('**/for-me.html');
  const hot = page.locator('a[href="index.html"]:visible').filter({hasText:'热榜'}).first();
  await hot.click();
  await page.waitForURL('**/index.html');
  await page.goto(base+'?q=Snowflake', {waitUntil:'networkidle'});
  assert(new URL(page.url()).searchParams.has('q'), 'Explicit searches must not redirect');
  await feedNavigation(page, () => page.goto(base+'for-me.html', {waitUntil:'domcontentloaded'}));
  await page.locator('#fmCustomize').click();
  await page.locator('#fmDefaultHome').uncheck();
  await page.locator('#fmReset').click();
  await page.locator('[data-task="platform"]').click();
  await page.locator('#fmNext').click();
  await page.locator('#fmDone').click();
  await feedNavigation(page, () => page.reload({waitUntil:'domcontentloaded'}));
  assert(!(await page.locator('#fmSetup').isVisible()), 'Returning users skip setup');
  assert.match(await page.locator('#fmMustList .fm-why').first().innerText(), /数据平台选型/);
  assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth+1));
  const returning = await page.locator('#fmMustList .fm-signal').first().boundingBox();
  assert(returning.y < 200, 'Returning readers also start with articles');
  fs.writeFileSync(path.join(out,`${width}-for-you-layout.json`), JSON.stringify({width,first_article:initial,first_reason:reason,returning_article:returning,header_position:'static'},null,2));
  await page.screenshot({path:path.join(out,`${width}-for-you.png`)});
  await page.locator('#fmCustomize').click();
  await page.screenshot({path:path.join(out,`${width}-for-you-setup.png`)});
  await page.keyboard.press('Escape');
  await feedNavigation(page, () => page.goto(base+'for-me.html#reading-settings', {waitUntil:'domcontentloaded'}));
  await page.locator('#fmSettings').waitFor({state:'visible'});
  assert(await page.locator('#fmSettings').isVisible(), 'Privacy deep link opens settings');
  assert(await page.locator('#fmBehaviorEnabled').isVisible());
  const control = await page.locator('#fmBehaviorEnabled').boundingBox();
  assert(control.y > 0 && control.y < 850, 'Deep-linked privacy control is within viewport');
  await page.screenshot({path:path.join(out,`${width}-for-you-privacy.png`)});
  await page.locator('#fmCloseSettings').click();
  await page.locator('#fmMustList .fm-signal-title').first().click();
  await feedNavigation(page, () => page.goBack({waitUntil:'domcontentloaded'}));
  assert(!(await page.locator('#fmSettings').isVisible()), 'Consumed privacy hash must not reopen settings on return');
  assert(await page.locator('#fmMustList .fm-signal').first().isVisible());
  assert.deepEqual(errors, []);
  await page.close();
};
